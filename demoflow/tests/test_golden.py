def test_the_span_NOISE_FLOOR_is_recomputed_from_the_shipped_ED_SERIES():
    """The span's noise floor, re-derived from the 24 published series rather than transcribed.

    THREE CLAIMS, and the middle one is what makes the other two reproducible:

    1. The four float summation orders the span names — forward, reversed, sorted, `fsum` —
       produce a BIT-IDENTICAL sum on every one of the 24 series. So "the maximum over the 24
       means x four orders" is a maximum over 24 values, not 96, and the rank vector's
       invariance across those orders is structural rather than measured.
    2. The floor AS EMITTED is `_LIMIT_EXPONENTIALS[0]`: the largest distance between
       `sum(series) / len(series)` — the arithmetic `output/rankings._scenario_mean` performs,
       float division included — and the exact rational mean of the same values.
    3. Dropping the division rounding gives `_LIMIT_EXPONENTIALS[1]`, which the span states
       beside it precisely because that omission is most of the difference between the two.
    """
    from fractions import Fraction

    frames = pipeline._load_all(GOLDEN_DATA_DIR)
    read = pipeline._ownership_reader(GOLDEN_DATA_DIR)
    geos = [g for g in Geography if g in set(frames.pop["geography"])]
    ed = pipeline._ed_dict(geos, frames, read, pipeline.CENTRAL_LEG)

    series = [xs for by_scen in ed.values() for xs in by_scen.values()]
    assert len(series) == 24, f"the span says 24 published means; the grid carries {len(series)}"

    worst_emitted = worst_sum_only = 0.0
    for xs in series:
        n = len(xs)
        orders = (sum(xs), sum(reversed(xs)), sum(sorted(xs)), math.fsum(xs))
        assert len(set(orders)) == 1, (
            f"the four summation orders disagree on a series ({sorted(set(orders))}) — the span "
            "states they are bit-identical, which is what makes its four-order census a no-op "
            "rather than a spread. Re-measure the floor as a maximum over 96 values, not 24")
        exact = sum((Fraction(x) for x in xs), Fraction(0)) / n
        for total in orders:
            worst_emitted = max(worst_emitted, abs(float(Fraction(total / n) - exact)))
            worst_sum_only = max(worst_sum_only, abs(float(Fraction(total) / n - exact)))

    assert f"{worst_emitted:.2e}" == _LIMIT_EXPONENTIALS[0], (
        f"the span publishes {_LIMIT_EXPONENTIALS[0]} as the worst deviation of an EMITTED mean "
        f"from exact arithmetic; the shipped series measure {worst_emitted:.2e}. This figure has "
        "been re-digited from an unreproducible reading twice — publish what this gate computes, "
        "and state the aggregation beside it")
    assert f"{worst_sum_only:.2e}" == _LIMIT_EXPONENTIALS[1], (
        f"the span publishes {_LIMIT_EXPONENTIALS[1]} for the same instrument WITHOUT the float "
        f"division; the shipped series measure {worst_sum_only:.2e}")
    assert worst_emitted > worst_sum_only, (
        "the division rounding cannot shrink the deviation — the span's claim that it is most "
        "of the figure has inverted, so the two figures are the other way round")


