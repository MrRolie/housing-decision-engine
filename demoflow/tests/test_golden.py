def test_the_committed_PAIR_is_refused_when_only_its_schema_version_disagrees():
    """Spec amendment #24(C), measured on the SHIPPED BYTES rather than on constructed documents.

    The published protocol had THREE steps and the identity §9 declares has FOUR members. This is
    the fourth, and the reason it was missing is structural: `schema_version` lives INSIDE the
    identity envelope, `payload_of` subtracts the envelope, so the pairing token cannot see it —
    the same property that makes the token computable without hashing itself.

    THE ORDER OF THE ASSERTIONS IS THE ARGUMENT. Every retired step is shown to PASS on the
    mutated pair FIRST — including the payload digest, one level below the token — so the fourth
    comparison is provably the only thing between a consumer and a pair whose two files disagree
    about the format they declare. The committed pair itself is asserted ACCEPTED at the top and
    the bottom of the same test, because a comparison that refused the shipped golden would be a
    louder bug than the hole it closes."""
    docs = {name: json.loads(_committed(name).read_text(encoding="utf-8"))
            for name in GOLDEN_ARTIFACTS}
    ranks, trips = docs["rankings.json"], docs["tripwire_baseline.json"]

    assert pair_identity_mismatches(ranks, trips) == (), (
        f"the COMMITTED pair is refused on {pair_identity_mismatches(ranks, trips)} — these two "
        f"files came off one run and every comparison the page publishes must accept them")
    assert ranks["schema"] != trips["schema"], (
        "the shipped documents carry the SAME `schema` string, so #24(C)'s reason for leaving "
        "`schema` out of the compared set no longer holds on these bytes")
    assert ranks["schema_version"] == trips["schema_version"]

