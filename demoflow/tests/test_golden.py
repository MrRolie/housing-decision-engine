"""The GOLDEN-DIFF gate (spec §10) — the committed artifacts, re-derived and compared.

`demoflow/artifacts/{rankings.json,tripwire_baseline.json}` are generated from the committed
data vintage by `scripts/gen_golden.py`, committed, and re-generated here. Everything the run
depends on is PINNED in `demoflow.golden` and imported — the data dir, `now`, the output names —
so this file re-declares no input and a change to the pin cannot pass unnoticed by the gate that
exists to notice changes.

WHAT A RED HERE MEANS IS THE POINT OF THE TASK, not a detail of it. IRCC restates a fraction of
its overlapping cells on every vintage and the ISQ workbooks are re-published, so a golden that
pins computed values WILL red on an upstream refresh with no code change — and a gate whose red
cannot be attributed to data-vs-code teaches its readers to re-mint reflexively, which is the
same as having no gate. So the comparison is made in TWO STEPS, in this order, and each names
its own cause:

  1. PARSED equality — a modeled quantity moved. Read the envelope: `data_vintage.source_hashes`
     moved => the DATA moved; `assumptions_hash` moved => the assumption SELECTION moved; neither
     moved => the CODE moved, which is the only one of the three that is a defect by default.
  2. BYTE equality — the values are identical and the SERIALIZATION moved (indent, key order,
     encoding, line endings). `artifacts._dump_json` pins all four; this is the assertion that
     makes those pins load-bearing.

Nothing is normalized out of either comparison. A golden with holes in its diff has stopped
pinning the thing it was built to pin; `artifacts/README.md` carries the same table for a reader
who meets the files without meeting this test.
"""
