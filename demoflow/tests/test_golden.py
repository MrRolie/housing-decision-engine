def test_the_readme_binds_the_BORROWED_PRIOR_flag_claim_to_the_emitted_rows():
    """The page's claim about the EMITTED flag, read off the emitted bytes.

    The disclosure only earns its place because the two row sets DIFFER, so both halves of that
    difference are measured against `rankings.json` itself rather than against the registry twice:
    which rows carry `borrowed_prior`, and which borrow the ownership curve and carry NOTHING.

    THE THIRD LEG IS THE DIRECTION, and it is the one a future change can falsify. Today every
    flagged row also borrows the curve, so the flag never OVER-states the borrow — the section
    says exactly that, and it is asserted as an EQUIVALENCE. A geography that starts carrying
    `borrowed_prior` without borrowing the curve (a coarser immigrant prior at a row that reads
    its own tenure table) is a legitimate state and it makes that sentence false, so this gate
    reds the PAGE rather than reading as a pipeline bug.

    THE FLAG'S MEANING IS BOUND TOO, at the one place it can be: the section says the flag fires
    on ONE OR BOTH of TWO immigrant-leg inputs, and `pipeline._borrowed_inputs` tests exactly the
    `*_provenance` fields `ImmigrantInputs` declares. A third provenance field would make the
    page's "two" wrong and the disjunction incomplete.
    """
    from dataclasses import fields

    from demoflow.demand.immigrant_inputs import ImmigrantInputs
    from demoflow.loaders import census

    text = README.read_text(encoding="utf-8")
    section = _borrow_section(text)
    rosters = _borrow_rosters(section)

    doc = json.loads(_committed("rankings.json").read_text(encoding="utf-8"))
    flagged = frozenset(row["geography"] for row in doc["rankings"]
                        if "borrowed_prior" in row["flags"])
    borrowers = frozenset(geo.value for geo in census._BORROWS_FROM)
    silent = borrowers - flagged

    assert flagged and silent, (
        f"the shipped rankings put `borrowed_prior` on {sorted(flagged)} and the curve-borrowers "
        f"are {sorted(borrowers)}, so the rows borrowing WITHOUT the flag are {sorted(silent)}. "
        "One of those two sets is empty — the flag and the ownership borrow have stopped "
        "disagreeing, and this section is a warning about a confusion that no longer exists. "
        "Re-measure and re-word it rather than deleting the gate")

    assert rosters["CARRY THE EMITTED FLAG"] == flagged, (
        f"artifacts/README.md names {sorted(rosters['CARRY THE EMITTED FLAG'])} as the rows "
        f"carrying `borrowed_prior`; the shipped `rankings.json` puts it on {sorted(flagged)}")
    assert rosters["BORROW THE CURVE AND CARRY NO FLAG"] == silent, (
        f"artifacts/README.md names {sorted(rosters['BORROW THE CURVE AND CARRY NO FLAG'])} as "
        f"the rows that borrow the ownership curve and carry no flag; MEASURED from the registry "
        f"and the shipped flags: {sorted(silent)}. These are the rows a reader who takes the "
        "emitted flag as 'this row's rates were borrowed' reads wrong, which is the whole subject "
        "of this section")

    # the DIRECTION, as an equivalence rather than a standing sentence
    assert (flagged <= borrowers) == says(section, "every flagged row does also borrow the curve"), (
        f"the flagged rows are {sorted(flagged)} and the curve-borrowers {sorted(borrowers)}; "
        f"rows flagged WITHOUT borrowing the curve: {sorted(flagged - borrowers)}. The section "
        "states that every flagged row also borrows the curve, so the flag never OVER-states — "
        "that sentence and the emitted bytes must agree in both directions")

    # ...and the flag's own SUBJECT: a disjunction over the provenance fields the code tests
    provenance_fields = [f.name for f in fields(ImmigrantInputs) if f.name.endswith("_provenance")]
    subject = _FLAG_SUBJECT_CLAUSE.findall(flat(section))
    assert len(subject) == 1 and subject[0] in _COUNT_WORDS, (
        f"the section states the flag's subject {len(subject)} times ({subject}) — the clause "
        f"{_FLAG_SUBJECT_CLAUSE.pattern!r} must reach exactly one number word")
    assert _COUNT_WORDS[subject[0]] == len(provenance_fields), (
        f"the section says the flag fires on {subject[0]} immigrant-leg inputs; "
        f"`ImmigrantInputs` declares {len(provenance_fields)} provenance fields "
        f"({provenance_fields}), and `pipeline._borrowed_inputs` tests them all")

    # ...and the SIZE of the under-statement, which is the sentence a consumer acts on
    under = _SILENT_CLAUSE.findall(flat(section))
    assert len(under) == 1 and under[0] in _COUNT_WORDS, (
        f"the section states how far the flag UNDER-states {len(under)} times ({under}) — the "
        f"clause {_SILENT_CLAUSE.pattern!r} must reach exactly one number word")
    assert _COUNT_WORDS[under[0]] == len(silent), (
        f"the section says the flag under-states at {under[0]} rows; MEASURED {len(silent)}: "
        f"{sorted(silent)}")
