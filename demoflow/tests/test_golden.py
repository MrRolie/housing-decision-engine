def _limit_paragraphs(span: str) -> dict[str, str]:
    """The NAMED-LIMITS span cut into its LIMIT paragraphs, keyed by their own labels.

    The guards are the point. Each anchor must occur EXACTLY ONCE and the pair must be ordered:
    `str.index` on a missing anchor raises, but a slice taken from a `find` that returned -1 is a
    region that cannot fail, and `tests/_prose_binding.py` records that trap by name."""
    out = {}
    for label, (begin, end) in _LIMIT_PARAGRAPHS.items():
        for anchor in (begin, end):
            assert span.count(anchor) == 1, (
                f"the NAMED-LIMITS span carries {span.count(anchor)} copies of {anchor!r}; each "
                "limit heading and the convergence heading must occur exactly once, or the "
                "per-paragraph slices below are taken over the wrong text")
        lo, hi = span.index(begin), span.index(end)
        assert 0 <= lo < hi, (
            f"limit {label}: {begin!r} must precede {end!r} in the NAMED-LIMITS span")
        out[label] = span[lo:hi]
    return out


