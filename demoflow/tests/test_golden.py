# and figures, so a lower-cased geography reds on the comparison rather than escaping the match.


def _at_page_precision(exact: float, as_written: str) -> str:
    """`exact`, formatted to the number of mantissa decimals the page chose.

    The page rounds — it writes `1.5e-03` for 1.544e-03 and `2.33e-05` for 2.3316e-05 — so a gate
    that demanded a fixed precision would forbid one of the two spellings the document already
    uses. Reading the precision OFF the page accepts any rounding the author picks and still
    refuses a wrong VALUE, which is the thing that can mislead."""
    mantissa = as_written.split("e")[0]
    decimals = len(mantissa.split(".")[1]) if "." in mantissa else 0
    return f"{exact:.{decimals}e}"


