def _match_golden(fresh_dir, name) -> dict:
    """Parsed equality, then byte equality — each with its own attribution (see the module
    docstring). Returns the committed document."""
    committed_bytes = _committed(name).read_bytes()
    fresh_bytes = (fresh_dir / name).read_bytes()
    committed_doc = json.loads(committed_bytes)
    fresh_doc = json.loads(fresh_bytes)

    if fresh_doc != committed_doc:
        # THE CASCADE IS ORDERED NARROWEST-CAUSE FIRST, and the `run_pairing` branch is LAST
        # because spec amendment #22(C) made that token the WIDEST field in the document: it now
        # binds both documents' canonical payload digests, so it moves for a model change too.
        #
        # THAT RE-ORDERING IS NOT COSMETIC. Under the pre-#22(C) payload, `run_pairing` moved for
        # the clock and for the other two envelope tokens ONLY, so "run_pairing differs and the
        # other two do not" identified the clock. Keep that branch above the payload test today
        # and every model change reports as a CLOCK change — the mis-attribution run 52 fixed,
        # reintroduced from the other side. So the PAYLOAD is tested before the token: the
        # documents' content outside the identity envelope is what a model change moves, and it is
        # the one thing `run_pairing` cannot move without.
        #
        # THE LAST TWO BRANCHES ARE BOTH REACHABLE, and that is checked by exhaustion rather
        # than assumed: the root key set is exactly the identity envelope's five positions plus
        # the payload, so a parsed inequality must land in one of {data_vintage,
        # assumptions_hash, payload, run_pairing, schema, schema_version} — the first four are
        # the branches above and the last two are the final else. What the final else CANNOT be
        # is a serialization difference, which is why it no longer says so: parsed equality is
        # tested first here and byte equality is asserted separately below, so an int/float leaf
        # that compares equal and serializes differently reds THERE, with its own attribution.
        #
        # WHAT REACHING THE `run_pairing` BRANCH MEANS: THIS document's envelope tokens and
        # THIS document's payload are byte-identical and only `run_pairing` differs. TWO CAUSES
        # REACH THAT STATE, and naming one of them was a mis-attribution measured 2026-08-23: the
        # token digests BOTH documents' payloads, so a change confined to the SIBLING file (a
        # tripwire band moved `indicators` alone) moves this document's `run_pairing` by itself
        # while nothing else here differs. `_match_golden` is per-document and cannot tell the two
        # apart, so the message names both and points at the sibling's own red in the same run --
        # both goldens are checked every time, so that red is always there to read. Since #22(C)
        # neither cause is the clock
        # — the clock reaches no emitted value on this tree — it is the TOKEN FUNCTION itself
        # (its payload definition or the canonical serialization it hashes). A clock-only re-mint
        # therefore no longer reds these tests at all. That WAS a real narrowing -- the old
        # token covered the clock, so moving the pin re-minted the goldens and forced a read --
        # and it is closed not here but by a DIRECT pin on the declared clock,
        # `test_the_goldens_declared_CLOCK_is_pinned_because_no_emitted_byte_holds_it` below.
        # The guard belongs there rather than in the token: a token that also hashed `now` would
        # answer two questions and so answer neither, which is the argument amendment #21 already
        # used to REFUSE hashing the tripwire declarations.
        cause = ("the DATA moved (data_vintage.source_hashes differs)"
                 if fresh_doc.get("data_vintage") != committed_doc.get("data_vintage") else
                 "the assumption SELECTION moved (assumptions_hash differs)"
                 if fresh_doc.get("assumptions_hash") != committed_doc.get("assumptions_hash")
                 else "the CODE moved — the envelope's DATA and ASSUMPTION tokens are IDENTICAL "
                      "and the document's CONTENT differs, so this is a model change, not an "
                      "upstream refresh"
                 if payload_of(fresh_doc) != payload_of(committed_doc)
                 else "the SIBLING DOCUMENT's payload moved, OR the PAIRING TOKEN FUNCTION did "
                      "(`run_pairing` differs while THIS document's payload and both its other "
                      "envelope tokens are byte-identical) — since spec amendment #22(C) the "
                      "token binds BOTH documents' payload digests, so a change confined to the "
                      "other file moves this one's token by itself. Read the other golden's own "
                      "red in this same run FIRST; if its payload held too, what changed is "
                      "`artifacts.pairing_token`'s own payload or the canonical serialization it "
                      "hashes"
                 if fresh_doc.get("run_pairing") != committed_doc.get("run_pairing")
                 else "the SCHEMA IDENTITY moved — `data_vintage`, `assumptions_hash`, the whole "
                      "payload and `run_pairing` all compare equal, so what differs is `schema` "
                      "or `schema_version`: the two envelope fields no branch above reads, and a "
                      "`schema_version` bump is a CONSUMER-BREAKING change, never a re-mint")
        pytest.fail(f"{name}: a modeled quantity moved — {cause}. {_REMINT}")

    assert fresh_bytes == committed_bytes, (
        f"{name}: every VALUE is identical and the SERIALIZATION moved — indent, key order, "
        f"encoding or line endings, all of which artifacts._dump_json pins. {_REMINT}")
    return committed_doc


