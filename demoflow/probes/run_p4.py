# --- Fact provenance registry (reused verbatim from run_p3.py) --------------
_FACTS: list["Fact"] = []


@dataclass(frozen=True)
class Fact:
    """A narrative figure carrying HOW this run obtained it.

    `derived` — computed from a CITED rate in THIS run (it changes when the source
                data changes), naming its inputs; `cited` — external, printed with
                its citation inline. The header is assembled from the mix actually
                present, so it cannot drift from the body.

    Known weakness (unchanged from P3): `derived` does NOT verify the value was
    computed — the tag is author-chosen. So the discipline is enforced by CODE:
    every ratio/band below is a live arithmetic expression over the cited rates,
    not a literal handed to `Fact.derived`.
    """

    text: str
    kind: str  # "derived" | "cited"
    source: str

    def __post_init__(self) -> None:
        _FACTS.append(self)

    @classmethod
    def derived(cls, value: object, how: str) -> "Fact":
        return cls(f"{value}", "derived", how)

    @classmethod
    def cited(cls, value: object, source: str) -> "Fact":
        return cls(f"{value}", "cited", source)

    def __str__(self) -> str:
        return self.text if self.kind == "derived" else f"{self.text} [cited: {self.source}]"


def _provenance_header() -> list[str]:
    derived = [f for f in _FACTS if f.kind == "derived"]
    cited = [f for f in _FACTS if f.kind == "cited"]
    lines = [
        "Written by `probes/run_p4.py`; nothing in this file is hand-edited.",
        "",
        "The catalogue sweep and dimension-level audit in §1-§3 are generated from the live "
        "WDS responses of the run that wrote this file. The fallback band in §4 is computed "
        "from CITED published rates: the input homeownership rates are external (each printed "
        "with its source and a verbatim quote); every RATIO and band endpoint is computed in "
        "code from those rates — no ratio is hand-typed.",
    ]
    if _FACTS:
        lines.append(
            f"§4 tags its headline figures with provenance. This run registered {len(_FACTS)}: "
            f"{len(derived)} DERIVED (computed from the cited rates in this same run) and "
            f"{len(cited)} CITED (external published rates, printed with the citation inline). "
            f"Untagged numerals elsewhere are: §1-§3 audit metadata (product ids, dimension "
            f"labels, counts of what was checked); the cited source rates and figures shown in "
            f"the §4 tables and verbatim quotes (traceable to the named articles); reference "
            f"labels (census/horizon years, age ranges); and the per-row ratios and inline "
            f"ranges computed beside those cited rates."
        )
    if cited:
        lines += ["", "Externally cited figures:"]
        lines += [f"- {f.text} — {f.source}" for f in cited]
    lines.append("")
    return lines


# --- helpers reused from run_p3.py ------------------------------------------
def _table_number(pid: object) -> str:
    """`98100231` -> `98-10-0231-01`, StatCan's published table-number form."""
    p = str(pid)
    if len(p) != 8 or not p.isdigit():
        raise ValueError(f"unexpected productId shape {pid!r}; cannot derive a table number")
    return f"{p[0:2]}-{p[2:4]}-{p[4:8]}-01"


def _table_url(pid: object) -> str:
    return f"https://www150.statcan.gc.ca/t1/tbl1/en/tv.action?pid={pid}01"


def _post(url: str, payload: list) -> list:
    req = urllib.request.Request(
        url, data=json.dumps(payload).encode(), headers={"Content-Type": "application/json"}
    )
    return json.loads(urllib.request.urlopen(req, timeout=TIMEOUT).read())


# --- live hunt --------------------------------------------------------------
def _catalogue() -> list[dict]:
    raw = urllib.request.urlopen(WDS_LIST, timeout=TIMEOUT).read()
    return json.loads(raw)


def _title_cross_hits(cubes: list[dict]) -> list[tuple[str, str]]:
    """Cubes whose TITLE mentions immigrant AND tenure/ownership (any family)."""
    hits = []
    for c in cubes:
        pid = str(c.get("productId") or "")
        t = c.get("cubeTitleEn") or ""
        tl = t.lower()
        if any(k in tl for k in IMM_TITLE_KW) and any(k in tl for k in TEN_TITLE_KW):
            hits.append((pid, t))
    return sorted(set(hits))


def _meta_batch(pids: list[str]) -> dict[str, dict]:
    """Fetch metadata for many productIds; returns {pid: object}. Batched POST."""
    out: dict[str, dict] = {}
    for i in range(0, len(pids), META_CHUNK):
        batch = [{"productId": int(p)} for p in pids[i : i + META_CHUNK]]
        for r in _post(WDS_META, batch):
            obj = r.get("object") or {}
            pid = str(obj.get("productId") or "")
            if pid:
                out[pid] = obj
    return out


def _dim_names(obj: dict) -> list[str]:
    return [(d.get("dimensionNameEn") or "") for d in obj.get("dimension", []) or []]


def _immigrant_dims(obj: dict) -> list[str]:
    return [n for n in _dim_names(obj)
            if "immigrant" in n.lower() or "immigration" in n.lower()]


def _tenure_dims(obj: dict) -> list[str]:
    hits = []
    for d in obj.get("dimension", []) or []:
        n = (d.get("dimensionNameEn") or "").lower()
        members = [(m.get("memberNameEn") or "").lower() for m in d.get("member", [])]
        if "tenure" in n or any(("owner" in m or "renter" in m) for m in members):
            hits.append(d.get("dimensionNameEn"))
    return hits


def _geo_members(obj: dict) -> list[str]:
    for d in obj.get("dimension", []) or []:
        if (d.get("dimensionNameEn") or "").lower().startswith("geo"):
            return [(m.get("memberNameEn") or "") for m in d.get("member", [])]
    return []


class VacuousAuditError(RuntimeError):
    """A NOT-FOUND must be EARNED. Raised when the WDS answered but with an empty
    population (200 -> [] / {}), so no audit actually ran over it. Routes to
    UNCONFIRMED-PROBE-FAILED rather than laundering a vacuous response into a false
    NOT-FOUND (NS #1: a verification gate must REFUSE when it cannot verify — an
    empty response is 'unknown', never 'absent')."""


def _guard_audit_ran(cubes: list, families: list, meta: dict, cand_meta: dict) -> None:
    """Floor guard: RAISE (-> UNCONFIRMED) on any vacuous audit input, so a
    NOT-FOUND is honored only over an audit that actually ran on a non-empty
    population. Kept a standalone function so it can be mutation-tested."""
    if not cubes:
        raise VacuousAuditError("getAllCubesListLite returned an empty catalogue")
    if families and not meta:
        raise VacuousAuditError(
            "the metadata probe resolved 0 cubes though the candidate families were non-empty"
        )
    if not cand_meta:
        raise VacuousAuditError("the targeted candidate probe resolved 0 cubes")


def _hunt(note: list[str]) -> str:
    """Run the live hunt, append its record to `note`, return the verdict token.

    Verdict is one of:
      NOT-FOUND-AT-CMA          — audited: no free cube yields the CMA ratio.
      UNCONFIRMED-PROBE-FAILED  — the WDS did not answer; the audit could not run.
    The fallback band in §4 does NOT depend on this — it is external published
    literature — so an outage cannot suppress the deliverable, only the audit.
    """
    # --- §1 catalogue sweep (title-level) -----------------------------------
    note += ["## 1. Catalogue sweep — title-level immigrant × tenure cross", ""]
    cubes = _catalogue()
    cross = _title_cross_hits(cubes)
    note.append(f"- `getAllCubesListLite` -> {len(cubes)} cubes in catalogue.")
    note.append(f"- Titles mentioning immigrant/origin AND tenure/owner/rent ({len(cross)}):")
    for pid, t in cross:
        note.append(f"  - `{pid}` {t}")
    # Breakdown by product-family prefix, DERIVED from the live hits so the enumeration
    # accounts for ALL of them (not a hand-typed family list that can miss a hit).
    by_prefix = {p: sum(1 for pid, _ in cross if pid.startswith(p))
                 for p in sorted({pid[:2] for pid, _ in cross})}
    note += [
        "",
        f"Breakdown of the {len(cross)} hits by product-family prefix: {by_prefix}. None is a "
        "free Census immigrant × TENURE cross-tab: the `33` rows count enterprise OWNERS; the "
        "`46` rows are CHSP residential-property OWNERS (a numerator, not a rate; homeownership "
        "coverage excludes Québec); the rest matched a tenure keyword only as a TITLE SUBSTRING "
        "and are NOT about housing tenure — e.g. `37100127` on app-RENT-ices (apprentices) and "
        "the `98` pair on pa-RENT-s' (parents') citizenship. Title search alone cannot prove "
        "absence, so §2 audits at the DIMENSION level.",
        "",
    ]

    # --- §2 dimension-level audit (the auditable NOT-FOUND) ------------------
    note += ["## 2. Dimension-level audit — the auditable NOT-FOUND", ""]
    housing_pids = sorted({
        str(c.get("productId")) for c in cubes
        if str(c.get("productId") or "").startswith("98")
        and any(k in (c.get("cubeTitleEn") or "").lower() for k in HOUSING_TITLE_KW)
    })
    imm_pids = sorted({
        str(c.get("productId")) for c in cubes
        if str(c.get("productId") or "").startswith("98")
        and any(k in (c.get("cubeTitleEn") or "").lower() for k in IMM_TITLE_KW)
    })
    meta = _meta_batch(sorted(set(housing_pids) | set(imm_pids)))

    # Direction A: 98* housing cubes carrying an immigrant dimension.
    a_hits = []
    for pid in housing_pids:
        obj = meta.get(pid)
        if obj and _immigrant_dims(obj):
            a_hits.append((pid, obj))
    # Direction B: 98* immigrant cubes carrying a tenure dimension.
    b_hits = [(pid, meta[pid]) for pid in imm_pids
              if meta.get(pid) and _tenure_dims(meta[pid])]

    note += [
        f"Probed metadata for {len(meta)} distinct 98* cubes "
        f"({len(housing_pids)} housing-family, {len(imm_pids)} immigrant-family).",
        "",
        "**Direction A — 98* housing/dwelling/tenure/maintainer cubes carrying an "
        "IMMIGRANT dimension:**",
    ]
    for pid, obj in a_hits:
        ten = _tenure_dims(obj)
        note.append(
            f"  - `{pid}` {obj.get('cubeTitleEn')} — immigrant dim {_immigrant_dims(obj)}; "
            f"tenure dim {ten or 'NONE'}"
        )
    a_with_tenure = [pid for pid, obj in a_hits if _tenure_dims(obj)]
    note += [
        f"  -> {len(a_hits)} carry an immigrant dimension; {len(a_with_tenure)} of those ALSO "
        f"carry a tenure dimension. (Housing suitability, shelter-cost-to-income and labour "
        f"force are NOT tenure.)",
        "",
        "**Direction B — 98* immigrant/period-of-immigration cubes carrying a TENURE "
        "dimension:**",
        f"  -> {len(b_hits)} of {len(imm_pids)} immigrant cubes carry a tenure dimension: "
        f"`{[p for p, _ in b_hits]}`.",
        "",
    ]
    census_cross_exists = bool(a_with_tenure or b_hits)

    # --- §3 targeted candidate probe (plan's wrong id + near-misses) --------
    note += ["## 3. Targeted candidates — how each resolves", ""]
    cand_meta = _meta_batch([PLAN_WRONG_PID, *IMM_HOUSING_NO_TENURE, CHSP_OWNER_PID])

    plan_obj = cand_meta.get(PLAN_WRONG_PID, {})
    note.append(
        f"- **{PLAN_WRONG_PID}** (the plan's product id) resolves to "
        f"**\"{plan_obj.get('cubeTitleEn', '?')}\"** — dimensions "
        f"{_dim_names(plan_obj)}. Nothing to do with immigrant status or tenure; a plan-author "
        f"guess (same class as P3's candidates)."
    )
    for pid in IMM_HOUSING_NO_TENURE:
        obj = cand_meta.get(pid, {})
        note.append(
            f"- **{pid}** \"{obj.get('cubeTitleEn', '?')}\" — HAS an immigrant dimension "
            f"{_immigrant_dims(obj)} at CMA geography, but its housing axis is "
            f"{[n for n in _dim_names(obj) if n not in _immigrant_dims(obj)][-2:]}, NOT tenure "
            f"(owner/renter). No ownership rate derivable."
        )
    chsp = cand_meta.get(CHSP_OWNER_PID, {})
    chsp_geo = _geo_members(chsp)
    chsp_qc = [m for m in chsp_geo if m and ("Que." in m or "Québec" in m or "Quebec" in m)]
    note.append(
        f"- **{CHSP_OWNER_PID}** \"{chsp.get('cubeTitleEn', '?')}\" (CHSP) — dimensions "
        f"{_dim_names(chsp)}. It counts property OWNERS by immigration status (a numerator), "
        f"NOT owner households over total households, so it yields no ownership RATE; its "
        f"'Proportion of owners by immigration status' estimate is the owner-pool COMPOSITION, "
        f"not owners/population. Its {len(chsp_geo)} geographies include "
        f"{len(chsp_qc)} Québec-named members -> the Montréal/Québec CMA cells are absent "
        f"(the CHSP homeownership coverage gap)."
    )
    note.append("")

    # FLOOR GUARD (NS #1 — a verification gate must REFUSE when it cannot verify): a
    # WDS-up-but-EMPTY response (200 -> [] / {}) does NOT raise, so without this a
    # vacuous audit would launder straight into a false NOT-FOUND over a population of
    # zero. RAISE instead -> main routes it to UNCONFIRMED-PROBE-FAILED. A NOT-FOUND is
    # honored ONLY over an audit that actually ran on a non-empty population.
    _guard_audit_ran(cubes, sorted(set(housing_pids) | set(imm_pids)), meta, cand_meta)

    verdict = "NOT-FOUND-AT-CMA" if not census_cross_exists else "FOUND-CANDIDATE"
    if census_cross_exists:
        # A structural surprise: some cube DOES cross immigrant × tenure. Record it
        # loudly rather than silently proceeding to the fallback. (Kept auditable.)
        note += [
            "> UNEXPECTED: the dimension audit found a cube crossing immigrant status × "
            "tenure. This contradicts the recorded premise; the fallback band below is NOT a "
            "substitute for pulling that cube. See Direction A/B hits above. This probe records "
            "the surprise and does NOT invent a NOT-FOUND.",
            "",
        ]
    note += [
        f"## LIVE HUNT VERDICT: {verdict}",
        "",
        "No free StatCan cube publishes an immigrant/non-immigrant ownership RATE at the "
        "Montréal/Québec CMA level: §2 dimension-audited the title-selected candidate pool "
        "(every 98* cube whose title carries a housing OR an immigrant term — both directions) "
        "and found no immigrant × tenure cross. That title-selected pool is where such a cube "
        "MUST surface: under StatCan's naming a genuine immigrant×tenure cross-tab would carry "
        "an immigrant or a housing term in its title, so the residual reliance on title-"
        "selection is bounded, not exhaustive coverage of all 98* cubes. CHSP (`46*`) is an "
        "owners-numerator that excludes Québec (§3). Therefore the spec §6 documented-fallback "
        "path applies.",
        "",
    ]
    return verdict


# --- fallback band (CITED rates -> DERIVED ratio, network-independent) ------
def _fallback_band(note: list[str]) -> tuple[float, ...]:
    """Compute the bands from the cited rates.

    Returns (lo, center, hi, lo3, ctr3, hi3, combined_lo, combined_hi): the
    recommended fifth-year cross-provincial band, the year-3 tenure-anchor band
    (the dominant axis), and the full plausible range across all three tenure
    anchors (year 1/3/5) × geography.
    """
    ratios = {prov: rec / cdn for prov, (rec, cdn) in S1_YEAR5.items()}
    lo = min(ratios.values())
    hi = max(ratios.values())
    center = sum(ratios.values()) / len(ratios)
    lo_prov = min(ratios, key=ratios.get)
    hi_prov = max(ratios, key=ratios.get)

    pooled_ratio = S2_IMM_OWNED_PER_1000 / S2_CDNBORN_OWNED_PER_1000
    recent_ratio = S2_RECENT_OWNED_PER_1000 / S2_CDNBORN_OWNED_PER_1000

    # Register provenance: the studies are CITED; the band + illustration are DERIVED.
    Fact.cited(
        f"recent-immigrant vs Canadian-born fifth-year homeownership rates, 7 provinces "
        f"(e.g. Ontario 40.2% vs 47.8%)",
        f"Statistics Canada, catalogue {SOURCE1['catalogue']}, \"{SOURCE1['title']}\", "
        f"Chart 1, released {SOURCE1['release']}. {SOURCE1['url']}",
    )
    Fact.cited(
        f"owned units per 1,000 people: immigrants {S2_IMM_OWNED_PER_1000:.0f} (pooled) / "
        f"{S2_RECENT_OWNED_PER_1000:.0f} (recent 0-5yr) vs Canadian-born "
        f"{S2_CDNBORN_OWNED_PER_1000:.0f}",
        f"Statistics Canada, catalogue {SOURCE2['catalogue']}, \"{SOURCE2['title']}\", "
        f"released {SOURCE2['release']}. {SOURCE2['url']}",
    )
    f_lo = Fact.derived(f"{lo:.3f}", f"min province ratio ({lo_prov}: "
                        f"{S1_YEAR5[lo_prov][0]}/{S1_YEAR5[lo_prov][1]})")
    f_ctr = Fact.derived(f"{center:.3f}", "unweighted mean of the 7 province ratios")
    f_hi = Fact.derived(f"{hi:.3f}", f"max province ratio ({hi_prov}: "
                        f"{S1_YEAR5[hi_prov][0]}/{S1_YEAR5[hi_prov][1]})")
    f_pool = Fact.derived(f"{pooled_ratio:.3f}", "310/271 owned units per 1,000 (pooled)")
    f_rec = Fact.derived(f"{recent_ratio:.3f}", "115/271 owned units per 1,000 (recent 0-5yr)")

    # SECOND band — the TENURE-anchor axis, which is the DOMINANT uncertainty and
    # is orthogonal to the cross-provincial dispersion the fifth-year band above
    # captures. Computed at year 3 as a concrete alternative anchor, so Task 15's
    # robustness sweep grid (spec §"Run contract") can SEE it rather than only the
    # cross-province spread. year-3 ratio = year-3 recent-immigrant rate / same-
    # province Canadian-born rate (same denominators as the year-5 band).
