"""P4 — the Tranche-1 COARSE-NETTING immigrant/non-immigrant ownership RATIO.

THE QUESTION, precisely (spec §6): the coarse netting applies `p_imm(a) =
p_nonimm(a) × ratio`, where `ratio` is the **Census immigrant/non-immigrant
ownership RATIO at CMA level** (banded). Without it a new (rental-skewed)
immigrant reads as a new buyer and the ownership-flow inversion collapses — the
netting IS the showcase's originality claim, so a silent 1.0 is FORBIDDEN. This
probe sources that ratio and records it as a BANDED multiplier (point ± spread).

WHAT THE HUNT ESTABLISHED (recorded live below, so a re-run re-derives it):
there is NO free StatCan cube that publishes an immigrant/non-immigrant
ownership RATE at the Montréal/Québec CMA level. This is proven at the
DIMENSION level, not just by title:
  * Census (98*): NO cube crosses immigrant status × TENURE. The 98* cubes that
    carry an immigrant dimension (98100327 housing suitability, 98100328
    shelter-cost-to-income, 98100656 labour force) have NO tenure dimension; and
    NO 98* immigrant/period-of-immigration cube carries a tenure dimension.
  * CHSP (46*) is the only immigrant × home-ownership family, but it counts
    residential-property OWNERS (a numerator) — not owner households over total
    households — so it yields no ownership RATE; and its homeownership coverage
    EXCLUDES Québec (the CHSP gap), so the MTL/QC CMA cells do not exist there.

So the SPEC-SANCTIONED outcome (spec §6 "record a documented multiplier band
with `borrowed_prior` if the exact CMA cell is unavailable; NO silent 1.0") is a
documented fallback band, sourced from CITED published immigrant-vs-non-immigrant
homeownership figures, with the RATIO computed in code from those cited rates and
the whole thing flagged `borrowed_prior`.

ANTI-FABRICATION (the cardinal discipline): every figure below is either
  `cited`   — an external published rate, printed with its source + verbatim
              quote inline (the input homeownership rates), or
  `derived` — computed from those cited rates in THIS run (the ratios and the
              band endpoints).
No ratio is hand-typed. The `Fact` registry self-accounts for the mix, and the
note is GENERATED by running this script — never hand-edited.

WHY A BAND, NOT A POINT (recorded, not resolved here — a Task-15 finding): the
Tranche-1 arrival flow is dominated by RECENT immigrants, whose ownership is
rental-skewed; a POOLED all-immigrant ratio is ≥1 (established immigrants own at
native-or-higher rates) and would DEFEAT the netting. The band is built from the
recent-immigrant evidence; Task 15 declares the central value per the spec's
central-value rule (spec §"Run contract for banded assumptions"), and Tranche 2
replaces this coarse ratio with the years-since-landing S-curve.

Run:  cd demoflow && uv run python probes/run_p4.py
"""

